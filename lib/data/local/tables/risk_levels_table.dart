import 'package:drift/drift.dart';

/// Уровень риска актива.
///
/// Таблицей, а не перечислением в коде, по прямому требованию: трёх
/// стандартных градаций может не хватить, и человек должен уметь
/// переименовать их или добавить свою. Перечисление такого не позволяет —
/// его значения живут в коде и в индексах базы.
///
/// Риск здесь — это то, что человек сам объявил про свой актив, и ничего
/// больше. Приложение не оценивает инструменты и не знает рыночных данных.
class RiskLevels extends Table {
  TextColumn get id => text()();
  TextColumn get name => text()();

  /// Порядок от меньшего риска к большему. Именно он, а не имя, задаёт
  /// смысл: «высокий» — это не строка, а самый правый уровень шкалы.
  /// Разрывы в нумерации допустимы — важен только порядок.
  IntColumn get rank => integer()();

  IntColumn get colorValue => integer()();

  /// Максимально допустимая доля капитала в этом уровне, 0..100.
  /// `null` — порог не задан, предупреждения по этому уровню не бывает.
  ///
  /// Хранится здесь, а не в настройках, потому что порог принадлежит
  /// уровню: уровень переименовали или удалили — порог уезжает вместе с
  /// ним, а не остаётся висеть в prefs под ключом, которому ничего не
  /// соответствует.
  RealColumn get maxSharePercent => real().nullable()();

  BoolColumn get isCustom => boolean().withDefault(const Constant(false))();

  @override
  Set<Column> get primaryKey => {id};
}
