/// Что актив делает с деньгами.
///
/// Разделение не бухгалтерское, а житейское, и в этом его польза. Квартира
/// в собственности и квартира в ипотеке стоят одинаково, но одна приносит
/// аренду, а вторая забирает платёж — и в списке капитала они должны
/// выглядеть по-разному, иначе капитал показывает только размер, ничего не
/// говоря о направлении.
enum CashFlowType {
  /// Приносит доход: сдаваемая недвижимость, дивидендные бумаги, бизнес.
  income,

  /// Забирает деньги: кредит, ипотека, машина на обслуживании.
  liability,

  /// Не делает ни того ни другого: наличные, вещь для себя.
  neutral;

  String get storageKey => name;

  static CashFlowType fromStorageKey(String? key) =>
      CashFlowType.values.firstWhere(
        (type) => type.storageKey == key,
        orElse: () => CashFlowType.neutral,
      );
}
