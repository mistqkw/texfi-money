import 'package:flutter/material.dart';

/// Цвета, не зависящие от выбранной темы — используются в местах без
/// доступа к BuildContext (сидинг категорий в БД) и как палитра выбора
/// цвета категории/цели, единая для всех тем.
abstract final class AppColors {
  static const Color accent = Color(0xFF4A7DFB);
  static const Color income = Color(0xFF3ED598);
  static const Color expense = Color(0xFFFF6B6B);
  static const Color warning = Color(0xFFFFB648);

  /// Палитра категорий. Порядок задаёт приоритет выбора при автосоздании.
  ///
  /// Раньше здесь лежали четыре системных цвета плюс четыре насыщенных
  /// (фиолетовый, бирюзовый, розовый, лаймовый), и список категорий
  /// получался радугой из восьми максимально разведённых тонов — самый
  /// детский элемент интерфейса. Хуже того, сюда попадали `income`,
  /// `expense` и `warning`: цвет, которым помечен расход, стоял рядом с
  /// суммой расхода и переставал что-либо значить.
  ///
  /// Новый набор — восемь приглушённых тонов в одной полосе светлоты и с
  /// низкой насыщенностью. Категории по-прежнему различимы, но список
  /// читается как одна система, а семантические зелёный и красный
  /// остаются только за знаком суммы.
  static const List<Color> categoryPalette = [
    Color(0xFF7E96C4), // пасмурно-синий
    Color(0xFF8FA98C), // шалфей
    Color(0xFFC09578), // глина
    Color(0xFFB9A06A), // песок
    Color(0xFF9A8AB5), // лиловый
    Color(0xFF7FA6A6), // серо-бирюзовый
    Color(0xFFBE8F9C), // пыльная роза
    Color(0xFFA0A48E), // оливково-серый
  ];
}
