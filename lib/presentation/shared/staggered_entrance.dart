import 'package:flutter/material.dart';
import 'package:flutter_animate/flutter_animate.dart';

import '../../core/theme/app_motion.dart';

/// Ступенчатое появление элемента списка — тот же приём, что на главной в
/// TexFi f0kus.
///
/// Список операций приезжает разом, и без сдвига глазу не за что
/// зацепиться, чтобы заметить, что он перестроился: смена фильтра, выбор
/// другого профиля, возврат после добавления траты выглядели как мгновенная
/// подмена содержимого. Сдвиг в сорок миллисекунд между соседями делает
/// перестройку событием, которое видно, но не приходится ждать.
///
/// Отдельным виджетом, а не цепочкой `.animate()` по месту: этих списков в
/// приложении с десяток, и «как именно появляется элемент» должно
/// задаваться в одном месте — иначе половина экранов разъедется по
/// длительностям через пару правок.
class StaggeredEntrance extends StatelessWidget {
  const StaggeredEntrance({
    super.key,
    required this.index,
    required this.child,
  });

  /// Позиция в списке. Задержка растёт с ней, но не бесконечно.
  final int index;

  final Widget child;

  /// Сколько первых элементов расходятся по времени.
  ///
  /// Дальше задержка не растёт, и это главное здесь решение. Без потолка
  /// сотый элемент истории ждал бы четыре секунды — а список, который
  /// доезжает дольше, чем человек до него доскроллил, выглядит не
  /// оживлённым, а сломанным. Восемь — примерно экран: ровно то, что видно
  /// в момент появления, и разъезжается, остальное уже на месте.
  static const int maxSteps = 8;

  /// Задержка перед появлением элемента на позиции [index].
  ///
  /// Отдельным методом, чтобы потолок можно было проверить тестом: на
  /// длинном списке он и решает всё, а увидеть его отсутствие можно только
  /// на данных, которых в разработке обычно нет.
  static Duration delayFor(int index) =>
      AppMotion.stagger * (index < maxSteps ? index : maxSteps);

  @override
  Widget build(BuildContext context) {
    final delay = delayFor(index);
    return child
        .animate()
        .fadeIn(duration: AppMotion.fast, delay: delay)
        .slideY(begin: 0.08, end: 0, duration: AppMotion.fast, delay: delay);
  }
}
