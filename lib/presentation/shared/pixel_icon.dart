/// Рендерит спрайт [PixelIcons] квадратами по сетке — без сглаживания,
/// `size` делится поровну между пикселями. Полутон (`+`) рисуется тем же
/// цветом с меньшей непрозрачностью, поэтому иконка остаётся одноцветной.
class PixelSprite extends StatelessWidget {
  const PixelSprite({
    super.key,
    required this.pattern,
    this.size = 20,
    this.color,
  });

  final List<String> pattern;
  final double size;
  final Color? color;

  @override
  Widget build(BuildContext context) {
    final resolvedColor = color ?? IconTheme.of(context).color ?? Theme.of(context).colorScheme.onSurface;
    return SizedBox(
      width: size,
      height: size,
      child: CustomPaint(
        painter: _PixelSpritePainter(pattern: pattern, color: resolvedColor),
      ),
    );
  }
}

class _PixelSpritePainter extends CustomPainter {
  _PixelSpritePainter({required this.pattern, required this.color});

  final List<String> pattern;
  final Color color;

  @override
  void paint(Canvas canvas, Size size) {
    final rows = pattern.length;
    if (rows == 0) return;
    final cols = pattern.first.length;
    final cellW = size.width / cols;
    final cellH = size.height / rows;
    final solid = Paint()..color = color;
    // Полутон — тот же цвет, а не серый: иконка обязана оставаться одноцветной
    // и в тёмной теме, и на цветной подложке категории, и там, где ей задают
    // цвет извне. Серый на цветном фоне выглядел бы грязью.
    final shade = Paint()..color = color.withValues(alpha: _shadeAlpha);

    for (var y = 0; y < rows; y++) {
      final row = pattern[y];
      for (var x = 0; x < cols && x < row.length; x++) {
        final paint = switch (row[x]) {
          '#' => solid,
          '+' => shade,
          _ => null,
        };
        if (paint == null) continue;
        canvas.drawRect(
          Rect.fromLTWH(x * cellW, y * cellH, cellW + 0.5, cellH + 0.5),
          paint,
        );
      }
    }
  }

  /// Насколько бледнее полутон.
  ///
  /// Подбиралось по нижнему размеру, а не по крупному: на 18 пикселях
  /// разница должна читаться, но не расслаиваться на две отдельные фигуры.
  /// Ниже трети полутон пропадает на светлой теме, выше половины —
  /// перестаёт отличаться от заливки.
  static const double _shadeAlpha = 0.42;

  @override
  bool shouldRepaint(covariant _PixelSpritePainter oldDelegate) {
    return color != oldDelegate.color || pattern != oldDelegate.pattern;
  }
}

/// Готовый drop-in вместо `Icon(IconData)` для мест, уже завязанных на
/// каталог [PixelIcons] по строковому ключу (категории).
class PixelIcon extends StatelessWidget {
  const PixelIcon(this.pattern, {super.key, this.size = 20, this.color});

  factory PixelIcon.category(String key, {Key? key2, double size = 20, Color? color}) {
    return PixelIcon(PixelIcons.forCategoryKey(key), key: key2, size: size, color: color);
  }

  final List<String> pattern;
  final double size;
  final Color? color;

  @override
  Widget build(BuildContext context) {
    return PixelSprite(pattern: pattern, size: size, color: color);
  }
}
