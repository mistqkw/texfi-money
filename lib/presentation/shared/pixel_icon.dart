/// Пиксельные силуэты экосистемы TexFi (как `PixelSprite`/`PixelIcon`
/// в TexFi f0kus): узнаваемые формы без сглаживания и лишней
/// детализации — категории, таббар, иконки настроек.
///
/// Каждый спрайт — квадратная сетка 12×12: `#` — закрашенный пиксель, `+` —
/// полутон, любой другой символ — пусто. Ключи для категорий совпадают с
/// ключами [CategoryIcons] в `core/constants/category_icons.dart`, чтобы
/// отрисовка подтягивалась прямо по `CategoryEntity.iconKey`.
///
/// Сетка была 8×8 и местами 10×10, и это не работало: на восьми клетках у
/// иконки нет места ни на одну деталь сверх силуэта, и «зарплата»,
/// «фриланс» и «накопления» превращались в три похожих пятна. Двенадцать
/// клеток дают вилку с ножом, лапу с подушечками, гармошку чека — то, по
/// чему иконку узнают, не вчитываясь в подпись.
///
/// Полутон появился по той же причине. Набор одноцветный по устройству —
/// цвет приходит снаружи и меняется вместе с темой и категорией, — а без
/// второго тона любая внутренняя деталь либо сливается с заливкой, либо
/// прорезает в силуэте дыру. `+` рисуется тем же цветом с меньшей
/// непрозрачностью, поэтому окно в доме остаётся окном, а не отверстием.
